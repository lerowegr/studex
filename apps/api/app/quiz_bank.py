def sample_questions(count: int = 8) -> list[dict]:
    indices = random.sample(range(len(QUESTIONS)), k=min(count, len(QUESTIONS)))
    return [
        {"id": i, "q": QUESTIONS[i]["q"], "options": QUESTIONS[i]["options"]}
        for i in indices
    ]


def check_answers(questions: list[dict], answers: list[int]) -> int:
    score = 0
    for item, given in zip(questions, answers):
        original = QUESTIONS[int(item["id"])]
        if 0 <= int(given) < len(original["options"]) and int(given) == original["answer"]:
            score += 1
    return score
